import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  parseBillInfoPage,
  validateBillIndex
} from '../src/lib/bill-index-parser.js';

const SESSION_CODE = '26RS';
const SESSION_NAME = '2026 Regular Session';
const BASE_URL = 'https://legis.la.gov/legis/BillInfo.aspx';

const TYPE_CONFIG = {
  HB: { safetyMax: 1600, missThreshold: 100 },
  SB: { safetyMax: 800, missThreshold: 100 },
  HCR: { safetyMax: 300, missThreshold: 75 },
  SCR: { safetyMax: 250, missThreshold: 75 },
  HR: { safetyMax: 650, missThreshold: 100 },
  SR: { safetyMax: 450, missThreshold: 100 }
};

const args = process.argv.slice(2);
const DRY_RUN = args.includes('--dry-run');
const requestedTypeArg = args.find((a) => a.startsWith('--type='));
const requestedType = requestedTypeArg ? requestedTypeArg.split('=')[1].toUpperCase() : null;

if (requestedType && !TYPE_CONFIG[requestedType]) {
  throw new Error(`Unsupported --type=${requestedType}. Use HB, SB, HCR, SCR, HR, or SR.`);
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const sqlString = (value) => value == null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;

async function fetchBill(instrument) {
  const url = `${BASE_URL}?s=${SESSION_CODE}&b=${instrument}`;

  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const response = await fetch(url, {
        redirect: 'follow',
        headers: {
          'user-agent': 'LeLegis/0.1 (+https://legis.le-comrade.org)',
          accept: 'text/html,application/xhtml+xml'
        }
      });

      if (!response.ok) {
        if (response.status >= 500 && attempt < 3) {
          await sleep(400 * attempt);
          continue;
        }
        return null;
      }

      const html = await response.text();
      return parseBillInfoPage(html, instrument, url);
    } catch (error) {
      if (attempt === 3) throw error;
      await sleep(400 * attempt);
    }
  }

  return null;
}

async function discoverType(type, config) {
  const records = [];
  let consecutiveMisses = 0;
  let lastHit = 0;

  for (let number = 1; number <= config.safetyMax; number += 1) {
    const instrument = `${type}${number}`;
    const record = await fetchBill(instrument);

    if (record) {
      records.push(record);
      lastHit = number;
      consecutiveMisses = 0;
    } else {
      consecutiveMisses += 1;
    }

    if (number % 50 === 0) {
      console.log(`${type}: scanned through ${number}, found ${records.length}`);
    }

    if (lastHit > 0 && consecutiveMisses >= config.missThreshold) {
      console.log(`${type}: stopping after ${config.missThreshold} consecutive misses beyond ${type}${lastHit}`);
      break;
    }

    await sleep(35);
  }

  if (records.length === 0) {
    throw new Error(`${type}: no instruments discovered`);
  }

  return records;
}

function buildSql(records) {
  const lines = [
    '-- Generated by scripts/import-bills.js from official Louisiana Legislature BillInfo pages.',
    `-- Session: ${SESSION_NAME} (${SESSION_CODE})`
  ];

  for (const bill of records) {
    lines.push(`INSERT INTO bills (
  session_id,
  instrument,
  instrument_type,
  bill_number,
  origin_chamber,
  subject,
  official_description,
  official_status,
  normalized_status,
  source_url,
  last_synced_at
)
SELECT
  s.id,
  ${sqlString(bill.instrument)},
  ${sqlString(bill.instrumentType)},
  ${bill.billNumber},
  ${sqlString(bill.originChamber)},
  ${sqlString(bill.subject)},
  ${sqlString(bill.official_description)},
  ${sqlString(bill.official_status)},
  ${sqlString(bill.normalized_status)},
  ${sqlString(bill.source_url)},
  CURRENT_TIMESTAMP
FROM sessions s
WHERE s.session_code = ${sqlString(SESSION_CODE)}
ON CONFLICT(session_id, instrument) DO UPDATE SET
  instrument_type = excluded.instrument_type,
  bill_number = excluded.bill_number,
  origin_chamber = excluded.origin_chamber,
  subject = excluded.subject,
  official_description = excluded.official_description,
  official_status = excluded.official_status,
  normalized_status = excluded.normalized_status,
  source_url = excluded.source_url,
  last_synced_at = CURRENT_TIMESTAMP,
  updated_at = CURRENT_TIMESTAMP;`);
  }

  return `${lines.join('\n\n')}\n`;
}

function runWrangler(sqlPath) {
  const result = spawnSync(
    'npx',
    ['wrangler', 'd1', 'execute', 'lelegis', '--remote', `--file=${sqlPath}`],
    {
      stdio: 'inherit',
      shell: process.platform === 'win32'
    }
  );

  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`wrangler d1 execute exited with status ${result.status}`);
  }
}

function printSummary(validation, records) {
  console.log('');
  for (const type of ['HB', 'SB', 'HCR', 'SCR', 'HR', 'SR']) {
    if (validation.byType[type] > 0) {
      console.log(`${type} discovered: ${validation.byType[type]}`);
    }
  }
  console.log(`Total instruments discovered: ${validation.total}`);

  const sample = records.slice(0, 12).map((bill) => ({
    instrument: bill.instrument,
    chamber: bill.originChamber,
    subject: bill.subject,
    status: bill.official_status
  }));
  console.table(sample);
}

async function main() {
  const types = requestedType ? [requestedType] : Object.keys(TYPE_CONFIG);
  const all = [];

  for (const type of types) {
    console.log(`Discovering ${type} instruments for ${SESSION_CODE}...`);
    const records = await discoverType(type, TYPE_CONFIG[type]);
    all.push(...records);
  }

  all.sort((a, b) => {
    const typeOrder = ['HB', 'SB', 'HCR', 'SCR', 'HR', 'SR'];
    return typeOrder.indexOf(a.instrumentType) - typeOrder.indexOf(b.instrumentType)
      || a.billNumber - b.billNumber;
  });

  const validation = validateBillIndex(all);
  printSummary(validation, all);

  if (DRY_RUN) {
    console.log('Dry run only. No database changes were made.');
    return;
  }

  const dir = mkdtempSync(join(tmpdir(), 'lelegis-bills-'));
  const sqlPath = join(dir, 'bills.sql');

  try {
    writeFileSync(sqlPath, buildSql(all), 'utf8');
    runWrangler(sqlPath);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }

  console.log(`Bill index sync complete. Upserted ${validation.total} instruments.`);
}

main().catch((error) => {
  console.error(error?.stack ?? String(error));
  process.exitCode = 1;
});
