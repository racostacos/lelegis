import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  parseLegislatorListing,
  validateLegislators
} from '../src/lib/legislator-parser.js';

const HOUSE_URL = 'https://house.louisiana.gov/H_Reps/H_Reps_FullInfo';
const SENATE_URL = 'https://senate.la.gov/Senators_FullInfo';
const DRY_RUN = process.argv.includes('--dry-run');

const sqlString = (value) => value == null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
const sqlInt = (value) => Number.isInteger(value) ? String(value) : 'NULL';

async function fetchHtml(url) {
  const response = await fetch(url, {
    headers: {
      'user-agent': 'LeLegis/0.1 (+https://legis.le-comrade.org)',
      accept: 'text/html,application/xhtml+xml'
    }
  });
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  return response.text();
}

function buildSql(members) {
  const lines = [
    'PRAGMA foreign_keys = ON;',
    '-- Generated by scripts/import-legislators.js from official Louisiana Legislature listings.',
    '-- Current-seat importer for the active legislature.'
  ];

  for (const chamber of ['HOUSE', 'SENATE']) {
    lines.push(`UPDATE legislators SET is_active = 0 WHERE chamber = ${sqlString(chamber)};`);
  }

  for (const m of members) {
    lines.push(`UPDATE legislators SET\n  official_id = ${sqlString(m.official_id)},\n  first_name = ${sqlString(m.first_name)},\n  last_name = ${sqlString(m.last_name)},\n  display_name = ${sqlString(m.display_name)},\n  party = ${sqlString(m.party)},\n  email = ${sqlString(m.email)},\n  phone = ${sqlString(m.phone)},\n  office_address = ${sqlString(m.office_address)},\n  photo_url = ${sqlString(m.photo_url)},\n  profile_url = ${sqlString(m.profile_url)},\n  is_active = 1,\n  updated_at = CURRENT_TIMESTAMP\nWHERE chamber = ${sqlString(m.chamber)} AND district_number = ${sqlInt(m.district_number)};`);

    lines.push(`INSERT INTO legislators (official_id, first_name, last_name, display_name, chamber, district_number, party, email, phone, office_address, photo_url, profile_url, is_active)\nSELECT ${sqlString(m.official_id)}, ${sqlString(m.first_name)}, ${sqlString(m.last_name)}, ${sqlString(m.display_name)}, ${sqlString(m.chamber)}, ${sqlInt(m.district_number)}, ${sqlString(m.party)}, ${sqlString(m.email)}, ${sqlString(m.phone)}, ${sqlString(m.office_address)}, ${sqlString(m.photo_url)}, ${sqlString(m.profile_url)}, 1\nWHERE NOT EXISTS (\n  SELECT 1 FROM legislators WHERE chamber = ${sqlString(m.chamber)} AND district_number = ${sqlInt(m.district_number)}\n);`);
  }

  return `${lines.join('\n\n')}\n`;
}

function printDryRun(members) {
  const rows = members.map((m) => ({
    chamber: m.chamber,
    district: m.district_number,
    name: m.display_name,
    party: m.party,
    email: m.email ?? ''
  }));
  console.table(rows);
}

function runWrangler(sqlPath) {
  const result = spawnSync('npx', ['wrangler', 'd1', 'execute', 'lelegis', '--remote', `--file=${sqlPath}`], {
    stdio: 'inherit',
    shell: process.platform === 'win32'
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`wrangler d1 execute exited with status ${result.status}`);
}

async function main() {
  const [houseHtml, senateHtml] = await Promise.all([
    fetchHtml(HOUSE_URL),
    fetchHtml(SENATE_URL)
  ]);

  const house = parseLegislatorListing(houseHtml, { chamber: 'HOUSE', baseUrl: HOUSE_URL });
  const senate = parseLegislatorListing(senateHtml, { chamber: 'SENATE', baseUrl: SENATE_URL });
  const validation = validateLegislators(house, senate);
  const all = [...house, ...senate].sort((a, b) => a.chamber.localeCompare(b.chamber) || a.district_number - b.district_number);

  console.log(`House discovered: ${validation.house}`);
  console.log(`Senate discovered: ${validation.senate}`);
  console.log(`Total discovered: ${validation.total}`);

  if (DRY_RUN) {
    printDryRun(all);
    console.log('Dry run only. No database changes were made.');
    return;
  }

  const dir = mkdtempSync(join(tmpdir(), 'lelegis-legislators-'));
  const sqlPath = join(dir, 'legislators.sql');
  try {
    writeFileSync(sqlPath, buildSql(all), 'utf8');
    runWrangler(sqlPath);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }

  console.log('Legislator sync complete.');
  console.log('House active: 105');
  console.log('Senate active: 39');
  console.log('Total active: 144');
}

main().catch((error) => {
  console.error(error?.stack ?? String(error));
  process.exitCode = 1;
});
